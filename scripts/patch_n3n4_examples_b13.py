def main():
    shutil.copy(SRC, BAK)
    data = json.loads(SRC.read_text(encoding="utf-8"))
    words = data["words"]
    idx_set = set(i for i, _, _ in EX)
    for i, jp, cn in EX:
        words[i]["example"] = {"segments": [{"text": jp}], "cn": cn}
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    # ---- 质检 ----
    TEMPL = re.compile(r'店で|毎朝、私は|この場所は|ニュースでは|会議で')
    # 1) JSON reload
    reloaded = json.loads(SRC.read_text(encoding="utf-8"))
    # 2) 模板残留校验：全文件
    templ_all = [k for k, w in enumerate(reloaded["words"])
                 if TEMPL.search("".join(s.get("text", "") for s in (w.get("example") or {}).get("segments", [])))]
    # 3) 本次写入条目校验
    bad = []
    for i, jp, cn in EX:
        ex = reloaded["words"][i].get("example") or {}
        seg = "".join(s.get("text", "") for s in ex.get("segments", []))
        if seg != jp or ex.get("cn") != cn:
            bad.append(i)
        if TEMPL.search(seg):
            bad.append(("TEMPL", i))
    print(f"written={len(EX)} idx_set_ok={len(idx_set) == len(EX)}")
    print(f"template_residue_fullfile={len(templ_all)} -> {templ_all[:10]}")
    print(f"bad_entries={bad}")
    assert not templ_all, "模板句残留不为0！"
    assert not bad, f"条目校验失败: {bad}"
    print("ALL CHECKS PASSED ✅")


if __name__ == "__main__":
    main()
