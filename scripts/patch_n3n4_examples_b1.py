    for i, jp, cn in EX:
        w = words[i]
        old = w.get("example")
        w["example"] = {"segments":[{"text": jp}], "cn": cn}
        replaced.append((i, w["surface"], old))
    json.dump(data, open(PATH,"w",encoding="utf-8"), ensure_ascii=False, indent=2)
