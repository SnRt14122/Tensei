def main():
    if not SRC.exists():
        raise SystemExit("源文件不存在")
    shutil.copy(SRC, BAK)
    data = json.loads(SRC.read_text(encoding="utf-8"))
    words = data["words"] if isinstance(data, dict) else data
    idx = [t[0] for t in EX]
    assert min(idx) >= 0 and max(idx) < len(words), "索引越界"
    assert len(set(idx)) == len(idx), "索引重复"
    for i, jp, cn in EX:
        w = words[i]
        w["example"] = {
            "jp": jp,
            "cn": cn,
            "segments": [{"text": jp}],
        }
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"✅ 已写入 {len(EX)} 条（索引 {min(idx)}-{max(idx)}），备份: {BAK.name}")

if __name__ == "__main__":
    main()
