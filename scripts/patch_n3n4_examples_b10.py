def main():
    shutil.copy(SRC, BAK)
    data = json.loads(SRC.read_text(encoding="utf-8"))
    words = data["words"]
    indices = set()
    for i, jp, cn in EX:
        assert i not in indices, f"dup index {i}"
        indices.add(i)
        words[i]["example"] = {"segments": [{"text": jp}], "cn": cn}
    # quality assertions
    bad = 0
    for i, jp, cn in EX:
        seg = "".join(s.get("text", "") for s in words[i]["example"]["segments"])
        if TEMPL.search(seg):
            print(f"!! template residue at {i}: {seg}")
            bad += 1
    assert bad == 0, "template residue found"
    SRC.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"wrote {len(EX)} examples; template residue = {bad}; backup -> {BAK.name}")


if __name__ == "__main__":
    main()
